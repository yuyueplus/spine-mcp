import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdir, mkdtemp, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { projectRoot } from '../src/config.js';
import { fileSha256 } from '../src/file-hash.js';
const exec = promisify(execFile), root = path.join(projectRoot, 'native-bridge');
const index = process.argv.indexOf('--jdk');
const jdk = index >= 0 ? process.argv[index + 1]! : process.env.JAVA_HOME ?? 'C:\\Program Files\\Eclipse Foundation\\jdk-8.0.302.8-hotspot';
const bin = (name: string) => path.join(jdk, 'bin', name + (process.platform === 'win32' ? '.exe' : ''));
await mkdir(path.join(root,'build'),{recursive:true});const classes=await mkdtemp(path.join(root,'build','classes-'));
const names = (await readdir(path.join(root, 'src'))).filter(f => f.endsWith('.java')).sort();
await exec(bin('javac'), ['-encoding', 'UTF-8', '-source', '8', '-target', '8', '-d', classes, ...names.map(n => path.join(root, 'src', n))], { windowsHide: true, timeout: 60000 });
const jar = path.join(root, 'spine-editor-bridge.jar');
await exec(bin('jar'), ['cfm', jar, path.join(root, 'MANIFEST.MF'), '-C', classes, '.'], { windowsHide: true, timeout: 30000 });
const sources = [];for (const file of ['MANIFEST.MF', 'builds.json', ...names.map(n => 'src/' + n)].sort()) sources.push({ path: file, sha256: await fileSha256(path.join(root, file)) });
const bundle = { protocol: '1', jar: path.basename(jar), sha256: await fileSha256(jar), sourceSha256: createHash('sha256').update(JSON.stringify(sources)).digest('hex'), sources };
await writeFile(path.join(root, 'bundle.json'), JSON.stringify(bundle, null, 2) + '\n');
console.log(JSON.stringify({ ...bundle, java: (await exec(bin('javac'), ['-version'])).stderr.trim() }, null, 2));
